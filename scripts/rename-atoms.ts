async function renameAtoms() {
  let updated = 0;
  let skipped = 0;

  for (const [oldTitle, newTitle] of Object.entries(RENAMES)) {
    const tasks = await prisma.task.findMany({
      where: {
        title: oldTitle,
        resistance: { not: null },
      },
    });

    if (tasks.length > 0) {
      await prisma.task.updateMany({
        where: {
          title: oldTitle,
          resistance: { not: null },
        },
        data: {
          title: newTitle,
        },
      });
      updated += tasks.length;
      console.log(`✓ "${oldTitle}" → "${newTitle}" (${tasks.length})`);
    } else {
      skipped++;
    }
  }

  console.log(`\nUpdated: ${updated} atoms`);
  console.log(`Skipped (not found): ${skipped}`);

  await prisma.$disconnect();
}

renameAtoms().catch(console.error);
